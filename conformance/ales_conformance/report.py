"""Emit the docs-ready conformance table to conformance/report.md (generated; do not hand-edit)."""

from __future__ import annotations

import argparse
from collections.abc import Sequence
from datetime import UTC, datetime
from pathlib import Path

from ales_adapters.coverage import Manifest, manifest_report

from .contract import ConformanceReport

REPORT_PATH = Path(__file__).resolve().parents[1] / "report.md"
COVERAGE_PATH = REPORT_PATH.parents[1] / "docs" / "coverage-matrix.md"

LEVEL_NOTES = {
    "ENFORCING": "blocks revoked context on the instrumented read path",
    "INGESTION_ONLY": "emits revocation events; cannot block reads",
}


VERIFIED, UNVERIFIED, NOT_APPLICABLE = "VERIFIED", "UNVERIFIED", "n/a"


def verify_manifests(
    manifests: Sequence[Manifest], reports: Sequence[ConformanceReport]
) -> list[tuple[Manifest, str]]:
    """Tie each manifest to a conformance run.

    An adapter claiming ``retrieval_interception: supported`` is VERIFIED only when a conformance row whose
    name starts with its ``conformance_subject`` passed as ENFORCING; otherwise UNVERIFIED (including when its
    live-store row was not generated). Manifests without a retrieval claim are VERIFIED if a passing row
    exists for them (e.g. the filesystem connector's ingestion contract), else n/a.
    """
    result: list[tuple[Manifest, str]] = []
    for m in manifests:
        row = next(
            (r for r in reports if m.conformance_subject and r.adapter.startswith(m.conformance_subject)),
            None,
        )
        proven = row is not None and row.passed and row.enforcement_level in ("ENFORCING", "INGESTION_ONLY")
        if m.claims_retrieval:
            result.append((m, VERIFIED if proven and row.enforcement_level == "ENFORCING" else UNVERIFIED))  # type: ignore[union-attr]
        else:
            result.append((m, VERIFIED if proven else NOT_APPLICABLE))
    return result


def render_manifests(
    reports: Sequence[ConformanceReport], manifests: Sequence[Manifest] | None = None
) -> list[str]:
    rows = verify_manifests(manifests if manifests is not None else manifest_report(), reports)
    lines = [
        "## Capability manifests",
        "",
        "| adapter | enforcement | retrieval | memory | model context | tool egress | purge | session reset | conformance |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for m, state in rows:
        cells = [
            m.adapter,
            m.enforcement_level,
            m.retrieval_interception,
            m.memory_interception,
            m.model_context_interception,
            m.tool_egress_interception,
            m.physical_purge,
            m.session_reset,
            state,
        ]
        lines.append(
            "| "
            + " | ".join(
                c.replace("|", "/").split(":")[0] if i in (3, 4, 5, 7) else c.replace("|", "/")
                for i, c in enumerate(cells)
            )
            + " |"
        )
    lines += [
        "",
        (
            "`conformance`: VERIFIED = a passing contract run backs the claim; UNVERIFIED = the manifest claims "
            "`retrieval_interception: supported` but no passing run was generated for it (for live stores: the store "
            "was not reachable, or no contract row exists); `n/a` = no retrieval claim to verify. Full per-capability "
            "detail (including `partial:` scopes): `ales integrations inspect`."
        ),
        "",
    ]
    return lines


def summary_table(reports: Sequence[ConformanceReport]) -> list[str]:
    lines = [
        "| adapter | store | checks passed | purges | level |",
        "|---|---|---|---|---|",
    ]
    for r in reports:
        lines.append(f"| {r.adapter} | {r.store} | {r.summary} | {r.purges} | {r.enforcement_level} |")
    return lines


def render_markdown(
    reports: Sequence[ConformanceReport],
    manifests: Sequence[Manifest] | None = None,
    *,
    run_date: str | None = None,
) -> str:
    lines = [
        "<!-- GENERATED by python -m ales_conformance.report -->",
        "",
        "# Adapter conformance",
        "",
        f"Run date (UTC): {run_date or datetime.now(UTC).date().isoformat()}",
        "",
        *summary_table(reports),
    ]
    lines += [""] + render_manifests(reports, manifests)
    lines += ["## Checks", ""]
    for r in reports:
        lines += [f"### {r.adapter}", "", "| id | check | result | detail |", "|---|---|---|---|"]
        for c in r.checks:
            detail = c.detail.replace("|", "/")
            lines.append(f"| {c.id} | {c.name} | {'pass' if c.passed else 'FAIL'} | {detail} |")
        lines.append("")
    lines += [
        (
            "`store`: `in-memory` = process-local stand-in (DictRedis / InMemoryVectorBackend); `live store` = the "
            "contract was run against a real running Qdrant / PostgreSQL+pgvector / Redis (rows appear only when "
            "that store was reachable when the report was generated); `filesystem` = a temp directory tree."
        ),
        "",
        (
            "Enforcement contract (a-e): pre-revocation read allowed; post-revocation read blocked; blocked read "
            "carries a spec reason code; re-read after block stays blocked; a read from another source is "
            "unaffected. Optional physical-purge check (f), for adapters that own a store: after the revocation and an "
            "outbox dispatcher run the revoked object is gone from the raw store (read with the guard bypassed), the "
            "unrelated object is still there, and a second run is a harmless no-op; `n/a` where the adapter holds no "
            "data of its own (LangGraph middleware, filesystem connector). Ingestion contract (i1-i6): scan registers sources; delete emits `deleted`; content change "
            "emits `version_superseded`; ACL narrowing emits `acl_changed`; no spurious events."
        ),
        "",
        (
            "Coverage caveat: a pass means the adapter's guarded read path enforces. Direct access to the "
            "underlying store bypasses the adapter and is not covered."
        ),
        "",
    ]
    return "\n".join(lines)


def write_report(reports: Sequence[ConformanceReport], path: Path | None = None) -> Path:
    path = path or REPORT_PATH
    path.write_text(render_markdown(reports), encoding="utf-8")
    return path


def main() -> int:
    from ales_adapters.live_stores import unavailable_reason

    from .suite import LIVE_SUBJECTS, run_all

    parser = argparse.ArgumentParser(
        description="Run adapter contracts and generate the two coverage tables."
    )
    parser.add_argument("--require-live", action="store_true", help="require Qdrant, pgvector and Redis")
    args = parser.parse_args()
    if args.require_live:
        for _, store in LIVE_SUBJECTS:
            reason = unavailable_reason(store)
            if reason:
                parser.exit(1, reason + "\n")

    reports = run_all()
    date = datetime.now(UTC).date().isoformat()
    REPORT_PATH.write_text(render_markdown(reports, run_date=date), encoding="utf-8")
    coverage = [
        "# Coverage matrix",
        "",
        f"Run date (UTC): {date}",
        "",
        *summary_table(reports),
        "",
        "Each row covers reads through the named adapter. A live-store purge pass means the contract",
        "also checked the raw store after dispatch. The LangGraph and LlamaIndex contract rows use",
        "stand-ins for the node and retriever. S3, Azure Blob and webhook ingestion have no conformance",
        "run in this suite. See the [individual checks and manifests](../conformance/report.md).",
    ]
    COVERAGE_PATH.write_text("\n".join(coverage) + "\n", encoding="utf-8")
    print(f"wrote {REPORT_PATH} and {COVERAGE_PATH}")
    return 0 if all(r.passed for r in reports) else 1


if __name__ == "__main__":
    raise SystemExit(main())
